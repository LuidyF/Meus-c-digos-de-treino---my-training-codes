#Entrada inicial valores lista
lista = [10, 20, 30, 40, 50]

#mudança item posição 1
lista[1] = 200

#adição de valor ao final da lista
lista.append(600)

#inserção de item na lista
lista.insert(2, 300)
print(lista)

#apagar ultimo item da lista
lista.pop()
print(lista)

#apagar primeiro item da lista
lista.pop(0)
print(lista)
